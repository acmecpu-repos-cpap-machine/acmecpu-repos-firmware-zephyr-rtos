#define SSD1306_WIDTH           128
#define SSD1306_HEIGHT          64
#define SSD1306_BUFFER_SIZE   SSD1306_WIDTH * SSD1306_HEIGHT / 8

typedef enum {
    Black = 0x00, // Black color, no pixel
    White = 0x01  // Pixel is set. Color depends on OLED
} SSD1306_COLOR;

typedef enum {
    SSD1306_OK = 0x00,
    SSD1306_ERR = 0x01  // Generic error.
} SSD1306_Error_t;

static uint8_t SSD1306_Buffer[SSD1306_BUFFER_SIZE];

// Write the screenbuffer with changed to the screen
static void ssd1306_UpdateScreen(const struct device *display_dev, uint16_t x, uint16_t y) {
	struct display_buffer_descriptor buf_desc;
	buf_desc.buf_size = SSD1306_WIDTH;
	buf_desc.width = SSD1306_WIDTH;
	buf_desc.height = SSD1306_HEIGHT/8;
	buf_desc.pitch = SSD1306_WIDTH;


	// Write data to each page of RAM. Number of pages
    // depends on the screen height:
    //
    //  * 32px   ==  4 pages
    //  * 64px   ==  8 pages
    //  * 128px  ==  16 pages
    for(uint8_t i = 0; i < SSD1306_HEIGHT/8; i++) {
//        ssd1306_WriteCommand(0xB0 + i); // Set the current RAM page address.
//        ssd1306_WriteCommand(0x00);
//        ssd1306_WriteCommand(0x10);
//        ssd1306_WriteData(&SSD1306_Buffer[SSD1306_WIDTH*i],SSD1306_WIDTH);
        display_write(display_dev, x, y, &buf_desc, &SSD1306_Buffer[SSD1306_WIDTH*i]);
        y+=buf_desc.height;
    }
}

//    Draw one pixel in the screenbuffer
//    X => X Coordinate
//    Y => Y Coordinate
//    color => Pixel color
static void ssd1306_DrawPixel(uint8_t x, uint8_t y, SSD1306_COLOR color) {
    if(x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) {
        // Don't write outside the buffer
        return;
    }

    // Draw in the right color
    if(color == White) {
        SSD1306_Buffer[x + (y / 8) * SSD1306_WIDTH] |= 1 << (y % 8);
    } else {
        SSD1306_Buffer[x + (y / 8) * SSD1306_WIDTH] &= ~(1 << (y % 8));
    }
}

//Draw bitmap - ported from the ADAFruit GFX library
static void ssd1306_DrawBitmap(uint8_t x, uint8_t y, const unsigned char* bitmap, uint8_t w, uint8_t h, SSD1306_COLOR color)
{
    int16_t byteWidth = (w + 7) / 8; // Bitmap scanline pad = whole byte
    uint8_t byte = 0;

    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) {
        return;
    }

    for (uint8_t j = 0; j < h; j++, y++) {
        for (uint8_t i = 0; i < w; i++) {
            if (i & 7)
                byte <<= 1;
            else
                byte = (*(const unsigned char *)(&bitmap[j * byteWidth + i / 8]));
            if (byte & 0x80)
                ssd1306_DrawPixel(x + i, y, color);
        }
    }
    return;
}

void ssd1306_Fill(SSD1306_COLOR color) {
    /* Set memory */
    uint32_t i;

    for(i = 0; i < sizeof(SSD1306_Buffer); i++) {
        SSD1306_Buffer[i] = (color == Black) ? 0x00 : 0xFF;
    }
}

void c20x_screen_splash_start(void)
{
	const struct device * display_dev = app_display_device_get();
	if (display_dev != NULL) {
		ssd1306_Fill(White);
		ssd1306_DrawBitmap(0, 0, splash_logo_128x64, 128, 64, Black);
		ssd1306_UpdateScreen(display_dev, 0, 0);
	}
}
